
CREATE TABLE IF NOT EXISTS d4nte_bans (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid VARCHAR(36) NOT NULL,
  name VARCHAR(16) NOT NULL,
  ip VARCHAR(45) NOT NULL,
  reason TEXT NOT NULL,
  staff VARCHAR(16) NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  INDEX (uuid),
  INDEX (name),
  INDEX (ip)
);

CREATE TABLE IF NOT EXISTS d4nte_mutes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid VARCHAR(36) NOT NULL,
  name VARCHAR(16) NOT NULL,
  reason TEXT NOT NULL,
  staff VARCHAR(16) NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  INDEX (uuid),
  INDEX (name)
);

CREATE TABLE IF NOT EXISTS d4nte_kicks (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid VARCHAR(36) NOT NULL,
  name VARCHAR(16) NOT NULL,
  reason TEXT NOT NULL,
  staff VARCHAR(16) NOT NULL,
  created_at BIGINT NOT NULL,
  ip VARCHAR(45) NOT NULL
);

CREATE TABLE IF NOT EXISTS d4nte_jails (
  id VARCHAR(64) PRIMARY KEY,
  world VARCHAR(64) NOT NULL,
  x DOUBLE NOT NULL,
  y DOUBLE NOT NULL,
  z DOUBLE NOT NULL,
  yaw FLOAT NOT NULL,
  pitch FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS d4nte_jailings (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uuid VARCHAR(36) NOT NULL,
  name VARCHAR(16) NOT NULL,
  jail_id VARCHAR(64) NOT NULL,
  reason TEXT NOT NULL,
  staff VARCHAR(16) NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  INDEX (uuid),
  INDEX (name),
  FOREIGN KEY (jail_id) REFERENCES d4nte_jails(id) ON DELETE CASCADE
);